from datetime import datetime, timezone

def build_report(assessment, hosts, findings, events):
    lines = [f"# AETHRON Security Assessment — {assessment['name']}", '',
             f"**Status:** {assessment['status']}  ", f"**Generated:** {datetime.now(timezone.utc).isoformat()}  ",
             f"**Assessment ID:** `{assessment['id']}`", '', '## Objective', assessment['objective'], '',
             '## Authorized scope', '```text', assessment['scope_text'].strip(), '```', '',
             '## Executive summary',
             f"AETHRON recorded {len(hosts)} host observation(s) and {len(findings)} finding(s). "
             'Observations are not equivalent to confirmed vulnerabilities; validate each item before treating it as exploitable.', '',
             '## Environment observations']
    if not hosts: lines.append('No host observations recorded.')
    for host in hosts:
        lines += [f"### {host['address']} — {host['state']}"]
        ports = __import__('json').loads(host['ports_json'])
        if not ports: lines.append('No open TCP services observed.')
        for p in ports: lines.append(f"- TCP/{p['port']} · {p['service']} · {p.get('product','')} {p.get('version','')}")
    lines += ['', '## Findings']
    if not findings: lines.append('No validated findings have been recorded.')
    for f in findings:
        lines += [f"### [{f['severity'].upper()}] {f['title']}", f"- Host: {f['host']}", f"- Service: {f['service']}", f"- Confidence: {f['confidence']}", f"- Status: {f['status']}", '', '**Evidence**', '```text', f['evidence'], '```', '', '**Recommended remediation**', f['remediation'], '']
    lines += ['## Activity record']
    for e in events: lines.append(f"- `{e['at']}` **{e['kind']}** — {e['title']}: {e['detail']}")
    lines += ['', '---', 'Generated by AETHRON. Assessment results are limited to the supplied scope and evidence collected during this run.']
    return '\n'.join(lines)
